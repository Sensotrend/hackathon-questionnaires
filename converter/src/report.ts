// The conversion report (plan §5.7): what each questionnaire contains, which
// overrides shaped it, and every note the conversion made, for review.

import type { Questionnaire, QuestionnaireItem } from "fhir/r4";
import type { Overrides } from "./overrides.ts";
import type { Duplicate } from "./source/loader.ts";

export interface ReportEntry {
  slug: string;
  file: string;
  questionnaire: Questionnaire;
  overrides: Overrides;
  notes: string[];
}

const allItems = (items: QuestionnaireItem[] = []): QuestionnaireItem[] =>
  items.flatMap((item) => [item, ...allItems(item.item)]);

function counts(questionnaire: Questionnaire) {
  const items = allItems(questionnaire.item);
  const byType = new Map<string, number>();
  for (const item of items) {
    const type = item.repeats ? `${item.type} (repeating)` : item.type;
    byType.set(type, (byType.get(type) ?? 0) + 1);
  }
  const isScore = (item: QuestionnaireItem) => item.linkId.startsWith("score-");
  return {
    byType,
    groups: byType.get("group") ?? 0,
    questions: items.filter((item) => !["group", "display"].includes(item.type) && !isScore(item)).length,
    followUps: items.filter((item) => item.enableWhen !== undefined).length,
    scores: items.filter(isScore).length,
  };
}

const escape = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function conversionReport(entries: ReportEntry[], duplicates: Duplicate[]): string {
  const lines = [
    "# Conversion report",
    "",
    "Generated by `npm run convert` from `Esitieto_lomakkeet_hackathon_json/` and `converter/overrides/`. Don't edit by hand.",
    "",
    "| Questionnaire | Groups | Questions | Follow-ups | Scores | Notes |",
    "|---|---:|---:|---:|---:|---:|",
    ...entries.map(({ slug, questionnaire, notes }) => {
      const c = counts(questionnaire);
      return `| [${escape(questionnaire.title ?? slug)}](#${slug}) | ${c.groups} | ${c.questions} | ${c.followUps} | ${c.scores} | ${notes.length} |`;
    }),
    "",
    "Questions excludes groups, display texts and score items. Follow-ups are items shown only for a given answer.",
  ];

  if (duplicates.length > 0) {
    lines.push("", "Skipped as identical to an earlier export of the same revision:", "");
    for (const { file, duplicateOf } of duplicates) lines.push(`- \`${file}\` (same as \`${duplicateOf}\`)`);
  }

  for (const { slug, file, questionnaire, overrides, notes } of entries) {
    const c = counts(questionnaire);
    const overrideKeys = Object.keys(overrides).filter((key) => key !== "$comment");
    lines.push(
      "",
      `<a id="${slug}"></a>`,
      "",
      `## ${questionnaire.title}`,
      "",
      `- Source: \`${file}\``,
      `- Output: \`fhir/questionnaires/${slug}.json\`, \`fhir/codesystems/${slug}.json\``,
      `- Questionnaire: \`${questionnaire.url}\`, version \`${questionnaire.version}\`${questionnaire.code ? `, code ${questionnaire.code.map((code) => `${code.code} (${code.display})`).join(", ")}` : ""}`,
      `- Items: ${[...c.byType].map(([type, count]) => `${count} ${type}`).join(", ")}`,
      `- Overrides: ${overrideKeys.length > 0 ? overrideKeys.map((key) => `\`${key}\``).join(", ") : "none"}`,
    );
    if (notes.length > 0) {
      lines.push("", "Notes:", "");
      for (const note of notes) lines.push(`- ${note}`);
    }
  }

  return `${lines.join("\n")}\n`;
}
