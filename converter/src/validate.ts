// `npm run validate`: runs the HL7 FHIR Validator over everything in fhir/
// and writes a summary to fhir/validation.md. Fails on any error or fatal
// issue. Warnings and information are summarised, not failed on.

import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import type { Bundle, OperationOutcome, OperationOutcomeIssue } from "fhir/r4";
import { FHIR_DIR, VALIDATOR_JAR } from "./paths.ts";

export const VALIDATOR_VERSION = "6.10.4";
export const VALIDATOR_ARGS = ["-version", "4.0.1", "-ig", "hl7.fhir.uv.sdc#3.0.0"];
const SEVERITIES = ["fatal", "error", "warning", "information"] as const;

/** Why accepted warnings are accepted, matched against the message. */
const ACCEPTED: { pattern: RegExp; reason: string }[] = [
  {
    pattern: /^Constraint failed: dom-6:/,
    reason:
      "No narrative: the resources are generated and read by software; a narrative would only repeat the title. Best practice, not a rule.",
  },
  {
    pattern: /^There are no valid display names found for the code http:\/\/loinc\.org#.* for language\(s\) 'fi'/,
    reason:
      "The Questionnaires are in Finnish, and LOINC has no Finnish display for the instrument panels, so the English display is used.",
  },
];

export interface Issue {
  file: string;
  severity: OperationOutcomeIssue["severity"];
  message: string;
}

/** The validator's -output: one OperationOutcome per file, or a Bundle of them. */
export function readIssues(output: Bundle | OperationOutcome, root: string): Issue[] {
  const outcomes =
    output.resourceType === "Bundle"
      ? (output.entry ?? []).map((entry) => entry.resource as OperationOutcome)
      : [output];
  return outcomes.flatMap((outcome) => {
    const source = outcome.extension?.find((ext) => ext.url.endsWith("operationoutcome-file"))?.valueString ?? "?";
    const file = source === "?" ? source : relative(root, source);
    return (outcome.issue ?? []).map((issue) => ({
      file,
      severity: issue.severity,
      message: issue.details?.text ?? issue.diagnostics ?? "(no message)",
    }));
  });
}

/** Groups issues by severity and message, with local ids generalised so similar messages group together. */
export function summarise(issues: Issue[], fileCount: number): string {
  const generalise = (message: string) =>
    message
      .replace(/https:\/\/sensotrend\.com\/fhir\/CodeSystem\/[0-9a-f-]{36}/g, "<answer CodeSystem>")
      .replace(/\|[0-9a-f-]{36}/g, "");
  const groups = new Map<string, { severity: Issue["severity"]; message: string; files: Set<string>; count: number }>();
  for (const issue of issues) {
    const message = generalise(issue.message);
    const key = `${issue.severity}\n${message}`;
    const group = groups.get(key) ?? { severity: issue.severity, message, files: new Set(), count: 0 };
    group.files.add(issue.file);
    group.count++;
    groups.set(key, group);
  }
  const sorted = [...groups.values()].sort(
    (a, b) => SEVERITIES.indexOf(a.severity) - SEVERITIES.indexOf(b.severity) || b.count - a.count,
  );
  const total = (severity: Issue["severity"]) => issues.filter((issue) => issue.severity === severity).length;

  const lines = [
    "# Validation",
    "",
    `Generated by \`npm run validate\`: HL7 FHIR Validator ${VALIDATOR_VERSION}, \`${VALIDATOR_ARGS.join(" ")}\`, with \`fhir/codesystems/\` and \`fhir/definitions/\` loaded. Don't edit by hand.`,
    "",
    `${fileCount} files: ${SEVERITIES.map((severity) => `${total(severity)} ${severity}`).join(", ")}.`,
    "",
    "| Severity | Count | Files | Message | Accepted because |",
    "|---|---:|---:|---|---|",
    ...sorted.map((group) => {
      const accepted = ACCEPTED.find((rule) => rule.pattern.test(group.message));
      const reason = group.severity === "information" ? "" : (accepted?.reason ?? "**not accepted**");
      const message = group.message.replace(/\|/g, "\\|").replace(/\n/g, " ");
      return `| ${group.severity} | ${group.count} | ${group.files.size} | ${message} | ${reason} |`;
    }),
  ];
  return `${lines.join("\n")}\n`;
}

function main() {
  if (!existsSync(VALIDATOR_JAR)) {
    console.error(
      `${VALIDATOR_JAR} is missing. Download validator_cli.jar ${VALIDATOR_VERSION} from https://github.com/hapifhir/org.hl7.fhir.core/releases/tag/${VALIDATOR_VERSION} into tools/ (see the README).`,
    );
    process.exitCode = 1;
    return;
  }

  const list = (dir: string) =>
    readdirSync(join(FHIR_DIR, dir))
      .filter((file) => file.endsWith(".json") && file !== "index.json")
      .map((file) => join(FHIR_DIR, dir, file));
  const files = [...list("questionnaires"), ...list("codesystems"), ...list("definitions")];
  const outputPath = join(VALIDATOR_JAR, "..", "validation.json");

  console.log(`Validating ${files.length} files; the full log goes to tools/validation.log…`);
  const run = spawnSync(
    "java",
    [
      "-Dfile.encoding=UTF-8",
      "-jar",
      VALIDATOR_JAR,
      ...files,
      ...VALIDATOR_ARGS,
      "-ig",
      join(FHIR_DIR, "codesystems"),
      "-ig",
      join(FHIR_DIR, "definitions"),
      "-output",
      outputPath,
    ],
    { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 },
  );
  writeFileSync(join(VALIDATOR_JAR, "..", "validation.log"), `${run.stdout}${run.stderr}`);
  if (run.error !== undefined || !existsSync(outputPath)) {
    console.error(`The validator didn't run: ${run.error?.message ?? run.stderr.slice(-2000)}`);
    process.exitCode = 1;
    return;
  }

  const issues = readIssues(JSON.parse(readFileSync(outputPath, "utf8")), join(FHIR_DIR, ".."));
  const summary = summarise(issues, files.length);
  writeFileSync(join(FHIR_DIR, "validation.md"), summary);

  const failures = issues.filter((issue) => issue.severity === "error" || issue.severity === "fatal");
  const unaccepted = issues.filter(
    (issue) => issue.severity === "warning" && !ACCEPTED.some((rule) => rule.pattern.test(issue.message)),
  );
  console.log(summary.split("\n")[4]);
  for (const issue of [...failures, ...unaccepted].slice(0, 50)) {
    console.log(`${issue.severity} ${issue.file}: ${issue.message}`);
  }
  if (failures.length > 0) process.exitCode = 1;
}

if (process.argv[1] === new URL(import.meta.url).pathname) main();
